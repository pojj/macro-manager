async function seed() {
  const uri = process.env.MONGODB_URI;
  const dbName = process.env.DBNAME;

  if (!uri || !dbName) {
    console.error("Missing MONGODB_URI or DBNAME. Set them in .env.local or environment.");
    process.exit(1);
  }

  try {
    await mongoose.connect(uri, { dbName });
    console.log("Connected to MongoDB");

    const Ingredient = mongoose.models.Ingredient || mongoose.model(
      "Ingredient",
      new mongoose.Schema({
        name: { type: String, required: true },
        image_url: { type: String, required: false },
        addedAt: { type: Date, default: Date.now },
      })
    );

    // Deduplicate and get existing ingredient names to avoid duplicates
    const uniqueIngredients = [...new Set(INGREDIENTS.map((n) => n.trim()).filter(Boolean))];
    const existing = await Ingredient.find({}, "name").lean();
    const existingNames = new Set(existing.map((i) => i.name.toLowerCase().trim()));

    const toInsert = uniqueIngredients.filter(
      (name) => !existingNames.has(name.toLowerCase().trim())
    );

    if (toInsert.length === 0) {
      console.log("All ingredients already exist. Nothing to add.");
      process.exit(0);
    }

    const docs = toInsert.map((name) => ({ name }));
    const result = await Ingredient.insertMany(docs);

    console.log(`Seeded ${result.length} new ingredients.`);
    console.log(`Total ingredients in DB: ${existing.length + result.length}`);
  } catch (err) {
    console.error("Seed failed:", err);
    process.exit(1);
  } finally {
    await mongoose.disconnect();
    console.log("Disconnected from MongoDB");
  }
}

seed();
